import QRCode from 'qrcode';

export interface QRGenerateOptions {
  errorCorrectionLevel?: 'L' | 'M' | 'Q' | 'H';
  width?: number;
  margin?: number;
  color?: {
    dark?: string;
    light?: string;
  };
}

export async function generateQRPngDataUrl(
  content: string,
  options: QRGenerateOptions = {}
): Promise<string> {
  const opts = {
    errorCorrectionLevel: options.errorCorrectionLevel || 'M',
    width: options.width || 400,
    margin: options.margin !== undefined ? options.margin : 2,
    color: {
      dark: options.color?.dark || '#000000',
      light: options.color?.light || '#FFFFFF',
    },
  };
  return await QRCode.toDataURL(content, opts);
}

export async function generateQRSvgString(
  content: string,
  options: QRGenerateOptions = {}
): Promise<string> {
  const opts = {
    errorCorrectionLevel: options.errorCorrectionLevel || 'M',
    width: options.width || 400,
    margin: options.margin !== undefined ? options.margin : 2,
    color: {
      dark: options.color?.dark || '#000000',
      light: options.color?.light || '#FFFFFF',
    },
  };
  return await QRCode.toString(content, { ...opts, type: 'svg' });
}

export function downloadFile(dataUrlOrString: string, filename: string, isSvg: boolean = false) {
  const link = document.createElement('a');
  if (isSvg) {
    const blob = new Blob([dataUrlOrString], { type: 'image/svg+xml;charset=utf-8' });
    link.href = URL.createObjectURL(blob);
  } else {
    link.href = dataUrlOrString;
  }
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
    const textArea = document.createElement('textarea');
    textArea.value = text;
    textArea.style.position = 'fixed';
    textArea.style.opacity = '0';
    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();
    const successful = document.execCommand('copy');
    document.body.removeChild(textArea);
    return successful;
  } catch {
    return false;
  }
}

export async function shareContent(title: string, text: string, url?: string): Promise<boolean> {
  try {
    if (navigator.share) {
      await navigator.share({
        title,
        text,
        url: url || undefined,
      });
      return true;
    }
    return false;
  } catch (e) {
    console.warn('Share API cancelled or unsupported:', e);
    return false;
  }
}

