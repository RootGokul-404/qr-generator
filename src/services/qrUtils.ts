export function detectQRContentType(text: string): 'url' | 'email' | 'phone' | 'wifi' | 'geo' | 'json' | 'text' {
  const trimmed = text.trim();
  if (trimmed.startsWith('http://') || trimmed.startsWith('https://')) return 'url';
  if (trimmed.startsWith('mailto:')) return 'email';
  if (trimmed.startsWith('tel:') || trimmed.startsWith('sms:')) return 'phone';
  if (trimmed.startsWith('WIFI:')) return 'wifi';
  if (trimmed.startsWith('geo:')) return 'geo';
  if ((trimmed.startsWith('{') && trimmed.endsWith('}')) || (trimmed.startsWith('[') && trimmed.endsWith(']'))) {
    try {
      JSON.parse(trimmed);
      return 'json';
    } catch {
      // fallthrough to text
    }
  }
  return 'text';
}
